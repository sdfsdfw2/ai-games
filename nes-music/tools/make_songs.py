#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""把 songlib.py 的曲库编译成 6502 汇编可直接 include 的 src/songs.inc。

产出内容：
  period_sq_lo/hi, period_tri_lo/hi   60 个音符的 APU 周期表（前置 1 字节占位，
                                      使索引 1..60 可直接用 ,x 寻址）
  noise_period / noise_volume         8 种打击类型（同样前置 1 字节）
  song_count                         曲目数
  song_table                         每条 16 字节的固定长度记录
  song_XX_data                       6 字节事件流，以 $00 结束
  song_XX_name                       曲名汉字在 CN_MAP 中的索引序列
  song_XX_label                      曲目列表用的 ASCII 短名（0 结尾）
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from songlib import build, stats, NOISE_PERIOD, NOISE_VOLUME, NOTE_COUNT

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "songs.inc")


def byte_table(name, values, per_line=16):
    """输出 .byte 表，前置一个 0 字节让 1-based 索引可直接寻址。"""
    lines = [f"{name}:"]
    data = [0] + list(values)
    for i in range(0, len(data), per_line):
        lines.append("    .byte " + ",".join(f"${v:02X}" for v in data[i:i + per_line]))
    return lines


def main():
    d = build()
    st = stats(d)
    sq, tri = d["period_sq"], d["period_tri"]

    out = [
        "; Generated by tools/make_songs.py - do not edit by hand",
        "; APU period tables + compiled song event streams",
        "; Event format (6 bytes): dur, sq1, sq2, tri, noise, bar",
        ";   note 0 = mute, 1..60 = pitch index, $FE = hold, dur 0 = end of song",
        "",
    ]
    out += byte_table("period_sq_lo", [v & 0xFF for v in sq]) + [""]
    out += byte_table("period_sq_hi", [(v >> 8) & 0x07 for v in sq]) + [""]
    out += byte_table("period_tri_lo", [v & 0xFF for v in tri]) + [""]
    out += byte_table("period_tri_hi", [(v >> 8) & 0x07 for v in tri]) + [""]
    out += byte_table("noise_period", NOISE_PERIOD) + [""]
    out += byte_table("noise_volume", NOISE_VOLUME) + [""]

    out += [
        f"song_count = {len(d['songs'])}",
        "",
        "; song_table: 16 bytes per record (index = song_idx * 16)",
        ";  +0  .word data_ptr     +2  tempo(tick frames)  +3  kind",
        ";  +4  .word total_ticks  +6  .word name_ptr",
        ";  +8  name_len           +9  loop_count",
        ";  +10 .word label_ptr    +12..15 padding",
        "song_table:",
    ]

    for i, s in enumerate(d["songs"]):
        m = s["meta"]
        total = s["total"]
        cn_hex = " ".join(f"{ord(c):04X}" for c in m["cn"])
        out += [
            f"    ; {i:02d} {m['en']}  CN={cn_hex}",
            f"    .byte <song_{i:02d}_data, >song_{i:02d}_data, "
            f"{m['tempo']}, {m['kind']}",
            f"    .byte <{total}, >{total}, "
            f"<song_{i:02d}_name, >song_{i:02d}_name",
            f"    .byte {len(s['name'])}, {m['loop']}, "
            f"<song_{i:02d}_label, >song_{i:02d}_label",
            "    .byte 0, 0, 0, 0",
        ]
    out.append("")

    for i, s in enumerate(d["songs"]):
        out.append(f"song_{i:02d}_data:")
        for ev in s["events"]:
            out.append("    .byte " + ",".join(f"${v:02X}" for v in ev))
        out.append("    .byte $00            ; end of song")
        out.append("")
        out.append(f"song_{i:02d}_name:")
        out.append("    .byte " + ",".join(f"${v:02X}" for v in s["name"]))
        out.append("")
        out.append(f'song_{i:02d}_label:')
        label = s["meta"]["en"]
        codes = ",".join(f"${ord(c):02X}" for c in label)
        out.append(f"    .byte {codes},0")
        out.append("")

    with open(OUT, "w", encoding="ascii") as f:
        f.write("\n".join(out) + "\n")

    print(f"songs.inc 生成完毕：{len(d['songs'])} 首 / "
          f"{st['cn_chars']} 汉字 / {st['events']} 事件 / "
          f"约 {st['song_bytes']} 字节")
    print(f"  事件流 {st['detail']['events']} B + 曲目表 {st['detail']['tables']} B "
          f"+ 曲名 {st['detail']['names']} B")
    print(f"  CN_MAP = {d['CN']}")


if __name__ == "__main__":
    main()
